using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

namespace DuckGame.TS
{
    /// <summary>
    /// Final pass over the imported assets:
    ///  - UI sprites get the Sprite import type so they can be used in uGUI
    ///  - audio clips are wired into a runtime catalogue component for easy playback
    ///  - textures that are clearly masks/normals are kept as-is (not sprites)
    /// </summary>
    public static class TSFinalize
    {
        const string SpriteDir = "Assets/DuckGame/TSAssets/Sprites";
        const string TextureDir = "Assets/DuckGame/TSAssets/Textures";
        const string AudioDir = "Assets/DuckGame/TSAssets/Audio";
        const string RuntimeDir = "Assets/DuckGame/TSAssets/Runtime";

        [MenuItem("Duck Game/Import TS/Finalize (Sprites + Audio)")]
        public static void Run()
        {
            var report = new System.Text.StringBuilder();
            Directory.CreateDirectory(RuntimeDir);

            // ---------- 1. sprites ----------
            int sprSet = 0;
            foreach (var guid in AssetDatabase.FindAssets("t:Texture2D", new[] { SpriteDir }))
            {
                string p = AssetDatabase.GUIDToAssetPath(guid);
                var ti = AssetImporter.GetAtPath(p) as TextureImporter;
                if (ti == null) continue;
                if (ti.textureType != TextureImporterType.Sprite)
                {
                    ti.textureType = TextureImporterType.Sprite;
                    ti.spriteImportMode = SpriteImportMode.Single;
                    ti.mipmapEnabled = false;
                    ti.alphaIsTransparency = true;
                    ti.SaveAndReimport();
                    sprSet++;
                }
            }
            report.AppendLine("sprites converted = " + sprSet);

            // ---------- 2. audio catalogue component ----------
            var clips = AssetDatabase.FindAssets("t:AudioClip", new[] { AudioDir })
                .Select(AssetDatabase.GUIDToAssetPath)
                .OrderBy(x => x)
                .ToList();
            report.AppendLine("audio clips = " + clips.Count);

            // Emit a simple runtime class with a name->clip table filled at build time.
            var sb = new System.Text.StringBuilder();
            sb.AppendLine("// AUTO-GENERATED by TSFinalize. Do not edit by hand.");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("namespace DuckGame.TS");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Named lookup over every audio clip imported from Trials Survivors,");
            sb.AppendLine("    /// so gameplay code can play a sound by name without wiring references by hand.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public sealed class TSAudioCatalogue : MonoBehaviour");
            sb.AppendLine("    {");
            sb.AppendLine("        public static TSAudioCatalogue Instance { get; private set; }");
            sb.AppendLine("        readonly Dictionary<string, AudioClip> map = new Dictionary<string, AudioClip>();");
            sb.AppendLine("        public IReadOnlyDictionary<string, AudioClip> All => map;");
            sb.AppendLine("        public AudioSource Source { get; private set; }");
            sb.AppendLine();
            sb.AppendLine("        void Awake()");
            sb.AppendLine("        {");
            sb.AppendLine("            if (Instance != null && Instance != this) { Destroy(gameObject); return; }");
            sb.AppendLine("            Instance = this;");
            sb.AppendLine("            Source = gameObject.GetComponent<AudioSource>();");
            sb.AppendLine("            if (Source == null) Source = gameObject.AddComponent<AudioSource>();");
            sb.AppendLine("            Source.playOnAwake = false;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public void Register(string key, AudioClip clip)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (!string.IsNullOrEmpty(key) && clip != null) map[key] = clip;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public AudioClip Get(string key)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (string.IsNullOrEmpty(key)) return null;");
            sb.AppendLine("            return map.TryGetValue(key, out var c) ? c : null;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public void Play(string key, float volume = 1f)");
            sb.AppendLine("        {");
            sb.AppendLine("            var c = Get(key);");
            sb.AppendLine("            if (c == null) return;");
            sb.AppendLine("            Source.PlayOneShot(c, volume);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public void PlayMusic(string key, float volume = .6f)");
            sb.AppendLine("        {");
            sb.AppendLine("            var c = Get(key);");
            sb.AppendLine("            if (c == null) return;");
            sb.AppendLine("            Source.clip = c;");
            sb.AppendLine("            Source.loop = true;");
            sb.AppendLine("            Source.volume = volume;");
            sb.AppendLine("            Source.Play();");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            string runtimePath = RuntimeDir + "/TSAudioCatalogue.cs";
            File.WriteAllText(Path.GetFullPath(runtimePath), sb.ToString());
            AssetDatabase.Refresh();
            report.AppendLine("runtime component written = " + runtimePath);

            // ---------- 3. summary ----------
            int models = AssetDatabase.FindAssets("t:Model", new[] { "Assets/DuckGame/TSAssets/Models" }).Length;
            int prefabs = AssetDatabase.FindAssets("t:Prefab", new[] { "Assets/DuckGame/TSAssets/Prefabs" }).Length;
            int tex = AssetDatabase.FindAssets("t:Texture2D", new[] { TextureDir }).Length;
            int spr = AssetDatabase.FindAssets("t:Sprite", new[] { SpriteDir }).Length;

            report.AppendLine("");
            report.AppendLine("=== FINAL COUNTS ===");
            report.AppendLine("models   = " + models);
            report.AppendLine("prefabs  = " + prefabs);
            report.AppendLine("textures = " + tex);
            report.AppendLine("sprites  = " + spr);
            report.AppendLine("audio    = " + clips.Count);

            File.WriteAllText(Path.GetFullPath("docs/ts-final-report.txt"), report.ToString());
            Debug.Log("TS_FINAL_DONE " + report.ToString().Replace("\n", " | "));
        }
    }
}
